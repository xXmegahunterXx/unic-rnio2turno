/**
 * País da cidade do exterior (undefined quando não atribuído). Lança erro se o código não estiver na tabela ou se o
 * nome do feed não bater (cidade nova ou código reaproveitado: revise a tabela).
 */
export function paisExterior(cod: string, nmFeed: string): string | undefined {
  const e = PAIS_EXTERIOR[cod];
  if (!e) throw new Error(`[ZZ ${cod} ${nmFeed}] cidade do exterior sem país em scripts/data/lib/exterior.ts`);
  if (e[0] !== nmFeed.trim()) throw new Error(`[ZZ ${cod}] nome do feed "${nmFeed}" ≠ tabela de países "${e[0]}"`);
  return e[1] ?? undefined;
}
